// Heaviest break either table publishes. Past this the rate card says to
// contact an account manager, so we can't quote automatically.
export const DHL_MAX_KG = 70;

// Rounds the chargeable weight up to the next published break and returns
// that row's rate for the given zone index. null if past the table.
export function lookupRate(table, weightKg, zoneIndex) {
  const row = table.find(([kg]) => weightKg <= kg);
  if (!row) return null;
  const rate = row[zoneIndex + 1];
  return typeof rate === "number" ? rate : null;
}
